create function public.school_points()
returns table (school_id bigint, school text, gold int, silver int, bronze int, points int)
language sql stable security definer set search_path = '' as $$
  with s as (select * from public.settings where id = 1),
  placed as (
    select coalesce(a.school_id, t.school_id) as school_id, r.position, ev.kind
    from public.results r
    join public.events ev on ev.id = r.event_id
    left join public.athletes a on a.id = r.athlete_id
    left join public.relay_teams t on t.id = r.relay_team_id
  )
  select sc.id, sc.name,
    count(*) filter (where p.position = 1)::int,
    count(*) filter (where p.position = 2)::int,
    count(*) filter (where p.position = 3)::int,
    coalesce(sum(
      (case p.position when 1 then s.points_first when 2 then s.points_second when 3 then s.points_third else 0 end)
      * (case when p.kind = 'relay' then s.relay_points_multiplier else 1 end)
    ), 0)::int
  from public.schools sc
  cross join s
  left join placed p on p.school_id = sc.id
  where public.is_staff() or s.public_results
  group by sc.id, sc.name
  order by 6 desc, 3 desc, 4 desc, 5 desc, sc.name
$$;

-- Read-only results for the public page: names, schools and placings only (no DOB or photos).
create function public.public_results()
returns table (
  event_id bigint, event text, kind public.event_kind, category text, category_order int,
  "position" smallint, performance text, competitor text, school text
)
language sql stable security definer set search_path = '' as $$
  select ev.id, ev.name, ev.kind, c.name, c.sort_order, r.position, r.performance,
    coalesce(a.name, sc_t.name || ' ' || t.team_label),
    coalesce(sc_a.name, sc_t.name)
  from public.results r
  join public.events ev on ev.id = r.event_id
  join public.categories c on c.id = ev.category_id
  left join public.athletes a on a.id = r.athlete_id
  left join public.schools sc_a on sc_a.id = a.school_id
  left join public.relay_teams t on t.id = r.relay_team_id
  left join public.schools sc_t on sc_t.id = t.school_id
  where public.is_staff() or (select public_results from public.settings where id = 1)
  order by c.sort_order, ev.sort_order, ev.name, r.position
$$;

