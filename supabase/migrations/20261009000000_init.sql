-- Renumbers every athlete. p_order: 'school' | 'category' | 'name'.
create function public.allocate_bibs(p_order text, p_start int)
returns int
language plpgsql security definer set search_path = '' as $$
declare
  n int;
begin
  if not public.is_admin() then
    raise exception 'Only an admin can allocate bib numbers.';
  end if;
  if (select bibs_finalized from public.settings where id = 1) then
    raise exception 'Bib numbers are finalized. Un-finalize them first.';
  end if;
  if p_start is null or p_start < 1 then
    raise exception 'Starting bib must be a positive number.';
  end if;

  update public.athletes set bib = null where bib is not null;

  with ordered as (
    select a.id, row_number() over (
      order by
        case when p_order = 'school' then s.name end,
        case when p_order in ('school', 'category') then c.sort_order end,
        case when p_order = 'category' then s.name end,
        lower(a.name), a.id
    ) as rn
    from public.athletes a
    join public.schools s on s.id = a.school_id
    join public.categories c on c.id = a.category_id
  )
  update public.athletes a set bib = p_start + o.rn - 1
  from ordered o where o.id = a.id;

  get diagnostics n = row_count;
  update public.settings set bib_start = p_start where id = 1;
  return n;
end;
$$;

-- Gives bibs only to athletes who don't have one, continuing after the highest bib.
-- Allowed after finalization so late registrations can still get a number.
create function public.assign_missing_bibs()
returns int
language plpgsql security definer set search_path = '' as $$
declare
  next_bib int;
  n int;
begin
  if not public.is_admin() then
    raise exception 'Only an admin can allocate bib numbers.';
  end if;
  select greatest(coalesce(max(bib), 0) + 1, (select bib_start from public.settings where id = 1))
    into next_bib from public.athletes;

  with ordered as (
    select id, row_number() over (order by created_at, id) as rn
    from public.athletes where bib is null
  )
  update public.athletes a set bib = next_bib + o.rn - 1
  from ordered o where o.id = a.id;

  get diagnostics n = row_count;
  return n;
end;
$$;

create function public.set_bibs_finalized(p_value boolean)
returns void
language plpgsql security definer set search_path = '' as $$
begin
  if not public.is_admin() then
    raise exception 'Only an admin can finalize bib numbers.';
  end if;
  if p_value and exists (select 1 from public.athletes where bib is null) then
    raise exception 'Some athletes have no bib number yet.';
  end if;
  update public.settings set bibs_finalized = p_value where id = 1;
end;
$$;

