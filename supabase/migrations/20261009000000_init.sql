create function public.validate_athlete() returns trigger
language plpgsql set search_path = '' as $$
declare
  c public.categories;
  finalized boolean;
begin
  select * into c from public.categories where id = new.category_id;
  if c.gender <> new.gender then
    raise exception 'Category % is for %, but the athlete is %.', c.name, c.gender, new.gender;
  end if;
  if new.dob < c.dob_from or (c.dob_to is not null and new.dob > c.dob_to) then
    raise exception 'Date of birth % is not eligible for category %.', to_char(new.dob, 'DD-MM-YYYY'), c.name;
  end if;

  new.name := regexp_replace(trim(new.name), '\s+', ' ', 'g');

  if tg_op = 'UPDATE' then
    if new.bib is distinct from old.bib then
      select bibs_finalized into finalized from public.settings where id = 1;
      if not public.is_admin() and auth.uid() is not null then
        raise exception 'Only an admin can change bib numbers.';
      end if;
      if finalized and old.bib is not null then
        raise exception 'Bib numbers are finalized. Un-finalize them before changing an existing bib.';
      end if;
    end if;
    -- Moving to another category drops entries that no longer belong to it.
    if new.category_id <> old.category_id then
      delete from public.entries e
      using public.events ev
      where e.athlete_id = new.id and ev.id = e.event_id and ev.category_id <> new.category_id;
      delete from public.relay_members m where m.athlete_id = new.id;
    end if;
    if new.school_id <> old.school_id then
      delete from public.relay_members m where m.athlete_id = new.id;
    end if;
    new.updated_at := now();
  elsif new.bib is not null and not public.is_admin() and auth.uid() is not null then
    raise exception 'Only an admin can assign bib numbers.';
  end if;
  return new;
end;
$$;

create trigger athletes_validate
  before insert or update on public.athletes
  for each row execute function public.validate_athlete();

create function public.validate_entry() returns trigger
language plpgsql set search_path = '' as $$
declare
  a public.athletes;
  ev public.events;
  taken int;
begin
  select * into a from public.athletes where id = new.athlete_id;
  select * into ev from public.events where id = new.event_id;
  if ev.kind = 'relay' then
    raise exception 'Relay events are entered as teams on the Relays page, not as individual entries.';
  end if;
  if ev.category_id <> a.category_id then
    raise exception 'Event % is not part of this athlete''s category.', ev.name;
  end if;
  if ev.max_per_school is not null then
    select count(*) into taken
    from public.entries e join public.athletes x on x.id = e.athlete_id
    where e.event_id = new.event_id and x.school_id = a.school_id and e.athlete_id <> new.athlete_id;
    if taken >= ev.max_per_school then
      raise exception 'Limit reached: a school may enter at most % athlete(s) in %.', ev.max_per_school, ev.name;
    end if;
  end if;
  return new;
end;
$$;

create trigger entries_validate
  before insert or update on public.entries
  for each row execute function public.validate_entry();

-- Withdrawing an athlete from an event also removes their result in it.
create function public.cleanup_entry_result() returns trigger
language plpgsql set search_path = '' as $$
begin
  delete from public.results where event_id = old.event_id and athlete_id = old.athlete_id;
  return old;
end;
$$;

create trigger entries_cleanup_result
  after delete on public.entries
  for each row execute function public.cleanup_entry_result();

create function public.validate_relay_team() returns trigger
language plpgsql set search_path = '' as $$
declare
  ev public.events;
  taken int;
begin
  select * into ev from public.events where id = new.event_id;
  if ev.kind <> 'relay' then
    raise exception '% is not a relay event.', ev.name;
  end if;
  if ev.max_per_school is not null then
    select count(*) into taken from public.relay_teams
    where event_id = new.event_id and school_id = new.school_id and id <> new.id;
    if taken >= ev.max_per_school then
      raise exception 'Limit reached: a school may enter at most % team(s) in %.', ev.max_per_school, ev.name;
    end if;
  end if;
  new.team_label := upper(trim(new.team_label));
  return new;
end;
$$;

create trigger relay_teams_validate
  before insert or update on public.relay_teams
  for each row execute function public.validate_relay_team();

create function public.validate_relay_member() returns trigger
language plpgsql set search_path = '' as $$
declare
  t public.relay_teams;
  ev public.events;
  a public.athletes;
begin
  select * into t from public.relay_teams where id = new.team_id;
  select * into ev from public.events where id = t.event_id;
  select * into a from public.athletes where id = new.athlete_id;
  if a.school_id <> t.school_id then
    raise exception '% is not from this team''s school.', a.name;
  end if;
  if a.category_id <> ev.category_id then
    raise exception '% is not in the % category for this relay.', a.name, (select name from public.categories where id = ev.category_id);
  end if;
  if exists (
    select 1 from public.relay_members m join public.relay_teams t2 on t2.id = m.team_id
    where m.athlete_id = new.athlete_id and t2.event_id = t.event_id and m.team_id <> new.team_id
  ) then
    raise exception '% is already in another team for this relay.', a.name;
  end if;
  return new;
end;
$$;

create trigger relay_members_validate
  before insert or update on public.relay_members
  for each row execute function public.validate_relay_member();

create function public.validate_result() returns trigger
language plpgsql set search_path = '' as $$
declare
  ev public.events;
begin
  select * into ev from public.events where id = new.event_id;
  if ev.kind = 'relay' then
    if new.relay_team_id is null then
      raise exception 'Relay results must be recorded for a team.';
    end if;
    if not exists (select 1 from public.relay_teams where id = new.relay_team_id and event_id = new.event_id) then
      raise exception 'That team is not entered in %.', ev.name;
    end if;
  else
    if new.athlete_id is null then
      raise exception 'Individual results must be recorded for an athlete.';
    end if;
    if not exists (select 1 from public.entries where athlete_id = new.athlete_id and event_id = new.event_id) then
      raise exception 'That athlete is not entered in %.', ev.name;
    end if;
  end if;
  new.performance := trim(new.performance);
  return new;
end;
$$;

create trigger results_validate
  before insert or update on public.results
  for each row execute function public.validate_result();

