-- Interschool Sports Meet: core schema, validation rules and row-level security.

create type public.app_role as enum ('admin', 'entry');
create type public.gender as enum ('Boys', 'Girls');
create type public.event_kind as enum ('track', 'field', 'relay');

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text,
  full_name text not null default '',
  role public.app_role not null default 'entry',
  created_at timestamptz not null default now()
);

create table public.settings (
  id int primary key default 1 check (id = 1),
  meet_name text not null default 'Interschool Sports Meet',
  venue text not null default '',
  meet_date date,
  organiser text not null default '',
  principal_name text not null default '',
  director_name text not null default '',
  bib_start int not null default 1001 check (bib_start > 0),
  bibs_finalized boolean not null default false,
  points_first int not null default 5,
  points_second int not null default 3,
  points_third int not null default 1,
  relay_points_multiplier int not null default 2,
  public_results boolean not null default true,
  updated_at timestamptz not null default now()
);

create table public.schools (
  id bigint generated by default as identity primary key,
  name text not null unique check (length(trim(name)) > 0),
  short_code text unique,
  created_at timestamptz not null default now()
);

create table public.categories (
  id bigint generated by default as identity primary key,
  name text not null unique check (length(trim(name)) > 0),
  gender public.gender not null,
  dob_from date not null,
  dob_to date,
  sort_order int not null default 0,
  check (dob_to is null or dob_to >= dob_from)
);

create table public.events (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.categories (id) on delete cascade,
  name text not null check (length(trim(name)) > 0),
  kind public.event_kind not null default 'track',
  max_per_school int check (max_per_school is null or max_per_school > 0),
  sort_order int not null default 0,
  unique (category_id, name)
);

create table public.athletes (
  id bigint generated by default as identity primary key,
  school_id bigint not null references public.schools (id) on delete restrict,
  category_id bigint not null references public.categories (id) on delete restrict,
  name text not null check (length(trim(name)) > 0),
  dob date not null,
  gender public.gender not null,
  bib int unique check (bib is null or bib > 0),
  photo_path text,
  created_by uuid default auth.uid() references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create unique index athletes_no_duplicates on public.athletes (lower(trim(name)), school_id, dob);
create index athletes_school_idx on public.athletes (school_id);
create index athletes_category_idx on public.athletes (category_id);

-- Individual (track/field) event entries. Relay participation is recorded via relay_teams.
create table public.entries (
  athlete_id bigint not null references public.athletes (id) on delete cascade,
  event_id bigint not null references public.events (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (athlete_id, event_id)
);
create index entries_event_idx on public.entries (event_id);

create table public.relay_teams (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.events (id) on delete cascade,
  school_id bigint not null references public.schools (id) on delete cascade,
  team_label text not null default 'A',
  created_at timestamptz not null default now(),
  unique (event_id, school_id, team_label)
);

create table public.relay_members (
  team_id bigint not null references public.relay_teams (id) on delete cascade,
  athlete_id bigint not null references public.athletes (id) on delete cascade,
  leg smallint not null check (leg between 1 and 4),
  primary key (team_id, leg),
  unique (team_id, athlete_id)
);
create index relay_members_athlete_idx on public.relay_members (athlete_id);

create table public.results (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.events (id) on delete cascade,
  athlete_id bigint references public.athletes (id) on delete cascade,
  relay_team_id bigint references public.relay_teams (id) on delete cascade,
  position smallint not null check (position between 1 and 3),
  performance text not null default '',
  created_by uuid default auth.uid() references auth.users (id) on delete set null,
  created_at timestamptz not null default now(),
  check ((athlete_id is null) <> (relay_team_id is null)),
  unique (event_id, position),
  unique (event_id, athlete_id),
  unique (event_id, relay_team_id)
);

